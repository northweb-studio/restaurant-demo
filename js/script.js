const btnDE = document.getElementById("btn-de");
const btnEN = document.getElementById("btn-en");

function applyLanguage(lang) {

    const dict = translations[lang];

    document.querySelectorAll("[data-i18n]").forEach(el => {

        const key = el.getAttribute("data-i18n");

        if (dict[key] !== undefined) {
            el.innerHTML = dict[key];
        }

    });

    document.documentElement.setAttribute("lang", lang);

    if (lang === "de") {
        btnDE.classList.add("active");
        btnEN.classList.remove("active");
    } else {
        btnEN.classList.add("active");
        btnDE.classList.remove("active");
    }

    localStorage.setItem("language", lang);

}

btnDE.addEventListener("click", () => applyLanguage("de"));
btnEN.addEventListener("click", () => applyLanguage("en"));

// Set the initial language: remembered choice first, otherwise the
// visitor's browser/system language, defaulting to English.

const savedLanguage = localStorage.getItem("language");

if (savedLanguage) {

    applyLanguage(savedLanguage);

} else {

    const browserLanguage = navigator.language.toLowerCase();

    applyLanguage(browserLanguage.startsWith("de") ? "de" : "en");

}

// ================================
// NAVBAR BACKGROUND ON SCROLL
// ================================

const navbar = document.querySelector(".navbar");

window.addEventListener("scroll",()=>{

    if(window.scrollY > 60){

        navbar.classList.add("scrolled");

    }else{

        navbar.classList.remove("scrolled");

    }

});

// ================================
// MENU FILTER
// ================================

const filterButtons=document.querySelectorAll(".menu-filter button");

const cards=document.querySelectorAll(".menu-card");

filterButtons.forEach(button=>{

button.addEventListener("click",()=>{

filterButtons.forEach(btn=>btn.classList.remove("active"));

button.classList.add("active");

const filter=button.dataset.filter;

cards.forEach(card=>{

if(filter==="all"){

card.style.display="block";

}else{

if(card.classList.contains(filter)){

card.style.display="block";

}else{

card.style.display="none";

}

}

});

});

});

// ================================
// BACK TO TOP
// ================================

const topBtn=document.getElementById("topBtn");

window.addEventListener("scroll",()=>{

topBtn.style.display=window.scrollY>400?"block":"none";

});

topBtn.onclick=()=>{

window.scrollTo({

top:0,

behavior:"smooth"

});

};

// ================================
// GALLERY LIGHTBOX
